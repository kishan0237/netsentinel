"""TCP connect scanner (thread-pool based)."""

import concurrent.futures as futures
import socket
from typing import Optional

DEFAULT_TIMEOUT = 0.8


def scan_tcp_ports(ip: str, ports: list[int], timeout: float = DEFAULT_TIMEOUT,
                   max_workers: int = 512) -> list[dict]:
    """Scan a list of TCP ports on one host. Returns [{port_number, protocol, state}]."""
    results: list[dict] = []
    with futures.ThreadPoolExecutor(max_workers=max_workers) as pool:
        scan_futures = {pool.submit(_probe, ip, p, timeout): p for p in ports}
        for fut in futures.as_completed(scan_futures):
            port = scan_futures[fut]
            try:
                state = fut.result()
            except OSError:
                state = "filtered"
            results.append({"port_number": port, "protocol": "tcp", "state": state})
    return sorted(results, key=lambda r: r["port_number"])


def _probe(ip: str, port: int, timeout: float) -> str:
    try:
        with socket.create_connection((ip, port), timeout=timeout):
            return "open"
    except ConnectionRefusedError:
        return "closed"
    except (socket.timeout, OSError):
        return "filtered"


